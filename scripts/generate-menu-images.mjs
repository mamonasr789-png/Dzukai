function buildVerificationPrompt(product) {
  return (
    `You are a quality-control AI for a restaurant menu image pipeline.\n\n` +
    `The following image was generated for this menu item:\n` +
    `Name: "${product.name}"\n` +
    `Description: "${product.description}"\n\n` +
    `Evaluate the image strictly:\n` +
    `1. Is it a food/drink image? (not abstract, not people, not scenery)\n` +
    `2. Does it correctly represent this specific dish or drink?\n` +
    `3. Is the image restaurant-quality? (well-lit, appetizing, properly plated)\n\n` +
    `Respond ONLY with valid JSON (no markdown, no explanation):\n` +
    `{"match": true_or_false, "confidence": 0_to_100, "reason": "one sentence"}`
  );
}

// ── OpenAI DALL-E 3 generation ────────────────────────────────────────────────

async function generateImage(prompt) {
  const res = await fetch("https://api.openai.com/v1/images/generations", {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${OPENAI_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      model: DALL_E_MODEL,
      prompt,
      n: 1,
      size: DALL_E_SIZE,
      quality: DALL_E_QUALITY,
      response_format: "b64_json",
    }),
  });

  if (res.status === 429) {
    const retryAfter = parseInt(res.headers.get("retry-after") ?? "10", 10);
    console.log(`    ⏳ Rate limited, waiting ${retryAfter}s...`);
    await sleep(retryAfter * 1000);
    return generateImage(prompt);
  }

  if (!res.ok) {
    const body = await res.text();
    throw new Error(`OpenAI API error ${res.status}: ${body.slice(0, 200)}`);
  }

  const data = await res.json();
  return data.data[0].b64_json; // base64 string
}

// ── Anthropic Claude Vision verification ──────────────────────────────────────

async function verifyImage(b64Image, product) {
  const res = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: {
      "x-api-key": ANTHROPIC_KEY,
      "anthropic-version": "2023-06-01",
      "content-type": "application/json",
    },
    body: JSON.stringify({
      model: "claude-sonnet-4-6",
      max_tokens: 256,
      messages: [{
        role: "user",
        content: [
          {
            type: "image",
            source: { type: "base64", media_type: "image/png", data: b64Image },
          },
          {
            type: "text",
            text: buildVerificationPrompt(product),
          },
        ],
      }],
    }),
  });

  if (res.status === 429) {
    await sleep(15000);
    return verifyImage(b64Image, product);
  }

  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Anthropic API error ${res.status}: ${body.slice(0, 200)}`);
  }

  const msg = await res.json();
  const text = msg.content[0].text.trim();

  // Strip markdown code fences if present
  const jsonText = text.replace(/^```json?\s*/i, "").replace(/\s*```$/, "").trim();

  try {
    const parsed = JSON.parse(jsonText);
    return {
      match:      Boolean(parsed.match),
      confidence: Number(parsed.confidence ?? 0),
      reason:     String(parsed.reason ?? ""),
    };
  } catch {
    // If JSON parse fails, try to extract values
    const matchVal = /match.*?:\s*(true|false)/i.exec(text);
    const confVal  = /confidence.*?:\s*(\d+)/i.exec(text);
    return {
      match:      matchVal ? matchVal[1] === "true" : false,
      confidence: confVal  ? parseInt(confVal[1], 10) : 0,
      reason:     text.slice(0, 120),
    };
  }
}

// ── Save image ────────────────────────────────────────────────────────────────

function saveBase64Image(b64, filePath) {
  const buf = Buffer.from(b64, "base64");
  writeFileSync(filePath, buf);
}

// ── Utilities ─────────────────────────────────────────────────────────────────

function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }

function fmt(n, total) { return `[${String(n).padStart(String(total).length)}/${total}]`; }

// ── Core pipeline: process one product ───────────────────────────────────────

async function processProduct(product, index, total, state) {
  const { id, name } = product;
  const filePath  = join(IMAGES_DIR, `${id}.jpg`);
  const webPath   = `/images/menu/${id}.jpg`;
  const prefix    = `  ${fmt(index, total)} ${id.padEnd(6)} ${name.slice(0, 45)}`;

  // Skip if already done and not forced
  if (!argForce && existsSync(filePath) && state.manifest[id]) {
    console.log(`${prefix} ✓ already done`);
    return { status: "skipped" };
  }

  let bestAttempt = null; // { b64, verification } — saved even if below threshold

  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    const attemptLabel = MAX_ATTEMPTS > 1 ? ` (attempt ${attempt}/${MAX_ATTEMPTS})` : "";
    process.stdout.write(`${prefix}${attemptLabel} — generating...`);

    let b64;
    try {
      const prompt = buildGenerationPrompt(product, attempt);
      b64 = await generateImage(prompt);
      process.stdout.write(" verifying...");
    } catch (err) {
      console.log(` ❌ generation failed: ${err.message}`);
      await sleep(3000);
      continue;
    }

    let verification;
    try {
      verification = await verifyImage(b64, product);
    } catch (err) {
      console.log(` ⚠️  verification error: ${err.message} — accepting image`);
      // If verification fails due to API error, accept the image
      verification = { match: true, confidence: 70, reason: "verification unavailable" };
    }

    const { match, confidence, reason } = verification;
    const symbol = match && confidence >= MIN_CONFIDENCE ? "✓" : "✗";
    console.log(` ${symbol} ${confidence}% — ${reason}`);

    // Track best attempt so far (highest confidence)
    if (!bestAttempt || confidence > bestAttempt.verification.confidence) {
      bestAttempt = { b64, verification };
    }

    if (match && confidence >= MIN_CONFIDENCE) {
      saveBase64Image(b64, filePath);
      state.manifest[id] = webPath;
      delete state.failed[id];
      return { status: "generated", verification };
    }

    if (attempt < MAX_ATTEMPTS) {
      await sleep(1000); // brief pause before retry
    }
  }

  // All attempts exhausted — save best attempt anyway (no broken images)
  if (bestAttempt) {
    console.log(`  ${fmt(index, total)} ${id.padEnd(6)} ⚠️  saved best attempt (confidence: ${bestAttempt.verification.confidence}%)`);
    saveBase64Image(bestAttempt.b64, filePath);
    state.manifest[id] = webPath;
    state.failed[id] = { confidence: bestAttempt.verification.confidence, reason: bestAttempt.verification.reason };
    return { status: "saved_best", verification: bestAttempt.verification };
  }

  console.log(`  ${fmt(index, total)} ${id.padEnd(6)} ✗ completely failed — no image saved`);
  return { status: "failed" };
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  console.log("\n🍽️  Restaurant Menu Image Pipeline");
  console.log("══════════════════════════════════\n");

  const allProducts = parseProducts();
  console.log(`📋 Parsed ${allProducts.length} products from data.ts`);

  // Apply filters
  let products = allProducts;
  if (argOnly)     products = products.filter(p => argOnly.includes(p.id));
  if (argCategory) products = products.filter(p => p.category === argCategory);
  if (argFrom) {
    const idx = products.findIndex(p => p.id === argFrom);
    if (idx >= 0) products = products.slice(idx);
  }

  if (products.length === 0) {
    console.log("⚠️  No products match the given filters.");
    process.exit(0);
  }
  console.log(`🎯 Processing ${products.length} products`);

  if (argDryRun) {
    products.forEach((p, i) => console.log(`  ${i + 1}. [${p.id}] ${p.name}`));
    process.exit(0);
  }

  console.log(`⚙️  DALL-E 3 ${DALL_E_QUALITY} quality | Claude claude-sonnet-4-6 verification | min confidence ${MIN_CONFIDENCE}%\n`);

  const state = loadState();
  const stats = { generated: 0, skipped: 0, savedBest: 0, failed: 0 };

  // Process in batches of CONCURRENCY
  for (let i = 0; i < products.length; i += CONCURRENCY) {
    const batch = products.slice(i, i + CONCURRENCY);
    const results = await Promise.all(
      batch.map((p, j) => processProduct(p, i + j + 1, products.length, state))
    );

    results.forEach(r => {
      if (r.status === "generated")   stats.generated++;
      else if (r.status === "skipped")  stats.skipped++;
      else if (r.status === "saved_best") stats.savedBest++;
      else if (r.status === "failed")   stats.failed++;
    });

    // Persist state + manifest after every batch
    saveState(state);
    writeManifest(state.manifest);
  }

  // Final summary
  const total = products.length;
  console.log("\n══════════════════════════════════");
  console.log(`✅ Pipeline complete — ${total} products processed`);
  console.log(`   Generated (verified):   ${stats.generated}`);
  console.log(`   Skipped (already done): ${stats.skipped}`);
  console.log(`   Saved best (low conf.): ${stats.savedBest}`);
  console.log(`   Failed (no image):      ${stats.failed}`);
  console.log(`   Manifest entries:       ${Object.keys(state.manifest).length}`);
  console.log(`\n📁 Images saved to: public/images/menu/`);
  console.log(`📄 Manifest updated: src/lib/image-manifest.ts`);

  if (Object.keys(state.failed).length > 0) {
    console.log(`\n⚠️  Low-confidence images (consider manual review):`);
    Object.entries(state.failed).forEach(([id, info]) => {
      console.log(`   ${id}: ${info.confidence}% — ${info.reason}`);
    });
  }

  if (stats.failed > 0) {
    console.log(`\n❌ ${stats.failed} product(s) have no image. Re-run the script to retry.`);
    process.exit(1);
  }

  console.log("\n🚀 Build the app to serve local images: node node_modules/next/dist/bin/next build\n");
}

main().catch(err => {
  console.error("\n💥 Fatal error:", err.message);
  process.exit(1);
});
