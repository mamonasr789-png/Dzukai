/**
 * AI Image Pipeline for Restaurant Menu
 * ======================================
 * For every product:
 *   1. Generate a restaurant-quality food image via OpenAI DALL-E 3
 *   2. Verify the image with Claude Vision (Anthropic)
 *   3. If the image doesn't match the dish, regenerate (up to MAX_ATTEMPTS)
 *   4. Save the approved image locally to public/images/menu/{id}.jpg
 *   5. Update src/lib/image-manifest.ts with all local paths
 *
 * Usage:
 *   OPENAI_API_KEY=sk-... ANTHROPIC_API_KEY=sk-ant-... node scripts/generate-menu-images.mjs
 *
 * Resume: the script saves progress to scripts/pipeline-state.json and skips
 * products whose image file already exists.
 *
 * Selective run:
 *   node scripts/generate-menu-images.mjs --only u1,u2,u3
 *   node scripts/generate-menu-images.mjs --category uzkandziai
 *   node scripts/generate-menu-images.mjs --from s5   (start from product id)
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, createWriteStream } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const IMAGES_DIR = join(ROOT, "public", "images", "menu");
const DATA_TS   = join(ROOT, "src", "lib", "data.ts");
const MANIFEST  = join(ROOT, "src", "lib", "image-manifest.ts");
const STATE_FILE = join(ROOT, "scripts", "pipeline-state.json");

// ── Config ──────────────────────────────────────────────────────────────────

const OPENAI_KEY    = process.env.OPENAI_API_KEY;
const ANTHROPIC_KEY = process.env.ANTHROPIC_API_KEY;
const MAX_ATTEMPTS  = 3;          // max generation attempts per product
const MIN_CONFIDENCE = 72;        // minimum vision confidence to accept (0–100)
const CONCURRENCY   = 3;          // products processed in parallel
const DALL_E_SIZE   = "1024x1024";
const DALL_E_QUALITY = "standard"; // "standard" | "hd"
const DALL_E_MODEL  = "dall-e-3";

// ── CLI args ─────────────────────────────────────────────────────────────────

const args = process.argv.slice(2);
const argOnly     = args.includes("--only")     ? args[args.indexOf("--only") + 1].split(",") : null;
const argCategory = args.includes("--category") ? args[args.indexOf("--category") + 1]        : null;
const argFrom     = args.includes("--from")     ? args[args.indexOf("--from") + 1]             : null;
const argForce    = args.includes("--force");   // regenerate even if image exists
const argDryRun   = args.includes("--dry-run"); // parse + print products, don't generate

// ── Validation ────────────────────────────────────────────────────────────────

if (!argDryRun) {
  if (!OPENAI_KEY)    { console.error("❌  OPENAI_API_KEY is not set.\n    Set it: export OPENAI_API_KEY=sk-..."); process.exit(1); }
  if (!ANTHROPIC_KEY) { console.error("❌  ANTHROPIC_API_KEY is not set.\n    Set it: export ANTHROPIC_API_KEY=sk-ant-..."); process.exit(1); }
}

mkdirSync(IMAGES_DIR, { recursive: true });

// ── Product parser ────────────────────────────────────────────────────────────

function parseProducts() {
  const src = readFileSync(DATA_TS, "utf8");
  const products = [];
  // Match product lines, handling escaped quotes inside strings
  const idRe = /\{ id: "([^"]+)", name: "((?:[^"\\]|\\.)*)", description: "((?:[^"\\]|\\.)*)".*?category: "([^"]+)"/gs;
  let m;
  while ((m = idRe.exec(src)) !== null) {
    // Unescape any \" sequences in name/description
    const unescape = (s) => s.replace(/\\"/g, '"').replace(/\\n/g, ' ');
    products.push({ id: m[1], name: unescape(m[2]), description: unescape(m[3]), category: m[4] });
  }
  if (products.length === 0) throw new Error("Could not parse any products from data.ts");
  return products;
}

// ── State management ──────────────────────────────────────────────────────────

function loadState() {
  if (existsSync(STATE_FILE)) {
    try { return JSON.parse(readFileSync(STATE_FILE, "utf8")); } catch {}
  }
  return { manifest: {}, failed: {} };
}

function saveState(state) {
  writeFileSync(STATE_FILE, JSON.stringify(state, null, 2));
}

function writeManifest(manifest) {
  const entries = Object.entries(manifest)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, path]) => `  "${id}": "${path}"`)
    .join(",\n");
  writeFileSync(MANIFEST,
    `// Auto-generated by scripts/generate-menu-images.mjs — do not edit manually.\n` +
    `// Re-run the script to refresh images.\n` +
    `export const imageManifest: Record<string, string> = {\n${entries}\n};\n`
  );
}

